// isCJKBreakRune reports whether one code point may break a line (upstream
// cjkBreakRegex).
func isCJKBreakRune(r rune) bool {
	index := sort.Search(len(cjkBreakRanges), func(i int) bool { return cjkBreakRanges[i].hi >= r })
	return index < len(cjkBreakRanges) && r >= cjkBreakRanges[index].lo
}

// containsCJKBreak reports whether any code point in the string may break a
// line (upstream cjkBreakRegex.test).
func containsCJKBreak(value string) bool {
	for _, r := range value {
		if isCJKBreakRune(r) {
			return true
		}
	}
	return false
}
