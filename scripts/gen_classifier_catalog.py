#!/usr/bin/env python3
"""Convert upstream generated model data into ai/classifier_catalog.json.

Upstream source: pi/packages/ai/src/providers/data/*.json, generated by
packages/ai/scripts/generate-models.ts. The output follows the builtin catalog
shape but retains only classifier models, keyed by provider, API, and model ID.

Usage:
    python3 scripts/gen_classifier_catalog.py /path/to/pi [api] > ai/classifier_catalog.json
"""
import json
import sys
from pathlib import Path


def main() -> None:
    if len(sys.argv) not in (2, 3):
        print(__doc__, file=sys.stderr)
        sys.exit(2)
    data_dir = Path(sys.argv[1]) / "packages" / "ai" / "src" / "providers" / "data"
    api_filter = sys.argv[2] if len(sys.argv) == 3 else None
    if not data_dir.is_dir():
        print(f"error: {data_dir} not found — run upstream's generate-models first", file=sys.stderr)
        sys.exit(1)

    manifest = json.loads((data_dir / ".manifest.json").read_text())
    providers = {}
    for file in sorted(data_dir.glob("*.json")):
        if file.name.startswith("."):
            continue
        raw = json.loads(file.read_text())
        by_api = {}
        for api, entries in raw.items():
            if api_filter is not None and api != api_filter:
                continue
            classifiers = {}
            for identity, model in entries.items():
                if model.get("type") != "classifier":
                    continue
                prefix = "classifier:"
                model_id = identity[len(prefix):] if identity.startswith(prefix) else identity
                classifiers[model_id] = model
            if classifiers:
                by_api[api] = classifiers
        if by_api:
            providers[file.stem] = by_api

    output = {
        "_meta": {
            "schemaVersion": manifest["schemaVersion"],
            "generatedAt": manifest["generatedAt"],
            "upstreamManifestSHA256": manifest.get("structureHash"),
        },
        "providers": providers,
    }
    json.dump(output, sys.stdout, indent=1, sort_keys=True)
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
