// Regenerate: node scripts/gen_language_order.mjs ./pi > internal/highlight/lang_order.go
// The reference iterates Object.keys(languages) for auto-detection, i.e. the
// registration order in lib/index.js; equal-relevance ties settle by it. Pier
// registers languages from Go init order (file order), which is alphabetical and
// therefore differs (xml and yaml are registered early upstream).
import fs from 'node:fs';
import path from 'node:path';

const root = process.argv[2] ?? './pi';
const source = fs.readFileSync(path.join(root, 'node_modules/highlight.js/lib/index.js'), 'utf8');
const names = [...source.matchAll(/registerLanguage\('([^']+)'/g)].map((match) => match[1]);
if (names.length === 0) throw new Error('no registerLanguage calls found');
process.stdout.write(`// Code generated by scripts/gen_language_order.mjs from pi v1.4.0 highlight.js. DO NOT EDIT.
// Regenerate: node scripts/gen_language_order.mjs ./pi > internal/highlight/lang_order.go
package highlight

// referenceLanguageOrder is the reference's registration order, used only to
// settle equal-relevance ties in auto-detection.
var referenceLanguageOrder = []string{
${names.map((name) => `\t${JSON.stringify(name)},`).join('\n')}
}
`);
