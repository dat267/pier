#!/usr/bin/env python3
"""Generate tui/wordbreak_table.go from the Unicode Character Database.

Usage: python3 scripts/gen_wordbreak.py <ucd-dir> > tui/wordbreak_table.go

<ucd-dir> holds the Unicode 17.0.0 files WordBreakProperty.txt,
GraphemeBreakProperty.txt, emoji-data.txt, Scripts.txt, PropList.txt and
LineBreak.txt (https://www.unicode.org/Public/17.0.0/ucd/, the auxiliary/ and
emoji/ files flattened into one directory). Unicode 17 is the version of the
ICU 78 that Node's Intl.Segmenter uses.

Each code point gets the class ICU's word.txt (icu4c/source/data/brkitr/rules,
release 78.1) tailors from Word_Break, plus the flags its rule statuses need:

  $Extend      = Word_Break=Extend minus Han
  $ALetterPlus = (Word_Break=ALetter minus Han, Hiragana, Katakana and the
                 Hangul syllables) plus (LineBreak=Complex_Context minus
                 $Extend and Grapheme_Cluster_Break=Control)
  Hangul       = U+AC00..U+D7A3 ($HangulSyllable)
"""

import re
import sys

CLASSES = [
    "Other", "CR", "LF", "Newline", "Extend", "ZWJ", "RegionalIndicator",
    "Format", "Katakana", "HebrewLetter", "ALetter", "SingleQuote",
    "DoubleQuote", "MidNumLet", "MidLetter", "MidNum", "Numeric",
    "ExtendNumLet", "WSegSpace", "Hangul",
]
WB_NAMES = {
    "CR": "CR", "LF": "LF", "Newline": "Newline", "Extend": "Extend",
    "ZWJ": "ZWJ", "Regional_Indicator": "RegionalIndicator",
    "Format": "Format", "Katakana": "Katakana",
    "Hebrew_Letter": "HebrewLetter", "ALetter": "ALetter",
    "Single_Quote": "SingleQuote", "Double_Quote": "DoubleQuote",
    "MidNumLet": "MidNumLet", "MidLetter": "MidLetter", "MidNum": "MidNum",
    "Numeric": "Numeric", "ExtendNumLet": "ExtendNumLet",
    "WSegSpace": "WSegSpace",
}
FLAG_EXT_PICT = 1 << 5
FLAG_HIRAGANA = 1 << 6
FLAG_IDEOGRAPHIC = 1 << 7
FLAG_KANA_KANJI = 1 << 8

MAX = 0x110000
LINE = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([A-Za-z_]+)")


def load(path, wanted=None):
    values = {}
    with open(path, encoding="utf-8") as source:
        for line in source:
            match = LINE.match(line)
            if not match:
                continue
            lo = int(match[1], 16)
            hi = int(match[2], 16) if match[2] else lo
            value = match[3]
            if wanted is not None and value not in wanted:
                continue
            for cp in range(lo, hi + 1):
                values[cp] = value
    return values


def main():
    ucd = sys.argv[1]
    wb = load(f"{ucd}/WordBreakProperty.txt")
    gcb = load(f"{ucd}/GraphemeBreakProperty.txt", {"Control"})
    pict = load(f"{ucd}/emoji-data.txt", {"Extended_Pictographic"})
    scripts = load(f"{ucd}/Scripts.txt", {"Han", "Hiragana"})
    ideographic = load(f"{ucd}/PropList.txt", {"Ideographic"})
    complex_context = load(f"{ucd}/LineBreak.txt", {"SA"})

    props = [0] * MAX
    overlaps = 0
    for cp in range(MAX):
        cls = WB_NAMES.get(wb.get(cp, ""), "Other")
        han = scripts.get(cp) == "Han"
        hiragana = scripts.get(cp) == "Hiragana"
        if cls == "Extend" and han:
            cls = "Other"
        if 0xAC00 <= cp <= 0xD7A3:
            cls = "Hangul"
        elif cls == "ALetter" and (han or hiragana):
            cls = "Other"
        if cp in complex_context and cls != "Extend" and cp not in gcb:
            if cls not in ("Other", "ALetter"):
                # ICU's sets would overlap here; the classes below are
                # exclusive, so report it for review.
                overlaps += 1
                print(f"overlap U+{cp:04X} {cls}", file=sys.stderr)
            cls = "ALetter"
        value = CLASSES.index(cls)
        if cp in pict:
            value |= FLAG_EXT_PICT
        if hiragana:
            value |= FLAG_HIRAGANA
        if cp in ideographic:
            value |= FLAG_IDEOGRAPHIC
        if han or hiragana or cls == "Katakana":
            value |= FLAG_KANA_KANJI
        props[cp] = value

    ranges = []
    start = 0
    for cp in range(1, MAX + 1):
        if cp == MAX or props[cp] != props[start]:
            if props[start] != 0:
                ranges.append((start, cp - 1, props[start]))
            start = cp

    out = sys.stdout
    out.write("// Code generated by scripts/gen_wordbreak.py from the Unicode 17.0.0\n")
    out.write("// UCD (ICU 78 word.txt tailoring). DO NOT EDIT.\n\n")
    out.write("package tui\n\n")
    out.write("const (\n")
    for index, name in enumerate(CLASSES):
        suffix = " wbClass = iota" if index == 0 else ""
        out.write(f"\twb{name}{suffix}\n")
    out.write(")\n\n")
    out.write("// wbRanges lists every code point whose word-break properties are not\n")
    out.write("// zero (class Other, no flags), as sorted, disjoint inclusive ranges.\n")
    out.write("var wbRanges = [...]wbRange{\n")
    for lo, hi, value in ranges:
        out.write(f"\t{{0x{lo:X}, 0x{hi:X}, 0x{value:X}}},\n")
    out.write("}\n")
    print(f"{len(ranges)} ranges, {overlaps} overlaps", file=sys.stderr)


main()
