package highlight

import (
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// goldenManifestEntry names a fixture and the language it is highlighted with.
// golden_manifest.json is the single source of truth: gen_golden.mjs regenerates
// every entry's .html from the pinned highlight.js, and TestGoldenFixturesAreListed
// fails if a checked-in sample is missing from it.
type goldenManifestEntry struct {
	File     string `json:"file"`
	Language string `json:"language"`
}

func loadGoldenManifest(t *testing.T) []goldenManifestEntry {
	t.Helper()
	data, err := os.ReadFile("testdata/golden_manifest.json")
	if err != nil {
		t.Fatalf("read golden manifest: %v", err)
	}
	var entries []goldenManifestEntry
	if err := json.Unmarshal(data, &entries); err != nil {
		t.Fatalf("parse golden manifest: %v", err)
	}
	if len(entries) == 0 {
		t.Fatal("golden manifest is empty")
	}
	return entries
}

// TestGoldenFixturesAreListed guards the manifest: every checked-in sample must
// be listed, so a fixture cannot be silently left untested (which once hid 18
// broken language ports).
func TestGoldenFixturesAreListed(t *testing.T) {
	listed := map[string]bool{}
	for _, entry := range loadGoldenManifest(t) {
		listed[entry.File] = true
	}
	names, err := os.ReadDir("testdata")
	if err != nil {
		t.Fatalf("read testdata: %v", err)
	}
	for _, name := range names {
		if name.IsDir() || !strings.HasPrefix(name.Name(), "sample") || strings.HasSuffix(name.Name(), ".html") {
			continue
		}
		if !listed[name.Name()] {
			t.Errorf("%s is not in golden_manifest.json", name.Name())
		}
	}
}

// TestGoldenHighlight compares the port's HTML against highlight.js 10.7.3 on
// every fixture in golden_manifest.json. The .html files are generated by
// gen_golden.mjs against the pinned reference.
func TestGoldenHighlight(t *testing.T) {
	for _, tc := range loadGoldenManifest(t) {
		if !supportsLanguage(tc.Language) {
			t.Errorf("%s: language %q is not registered", tc.File, tc.Language)
			continue
		}
		code, err := os.ReadFile(filepath.Join("testdata", tc.File))
		if err != nil {
			t.Fatalf("read %s: %v", tc.File, err)
		}
		want, err := os.ReadFile(filepath.Join("testdata", tc.File+".html"))
		if err != nil {
			t.Fatalf("read golden %s: %v", tc.File, err)
		}
		result, err := Highlight(string(code), tc.Language)
		if err != nil {
			t.Fatalf("highlight %s: %v", tc.File, err)
		}
		got := RenderHTML(result.Nodes)
		if got == string(want) {
			continue
		}
		t.Errorf("%s (%s): output differs", tc.File, tc.Language)
		gotLines := strings.Split(got, "\n")
		wantLines := strings.Split(string(want), "\n")
		for i := 0; i < len(gotLines) || i < len(wantLines); i++ {
			var g, w string
			if i < len(gotLines) {
				g = gotLines[i]
			}
			if i < len(wantLines) {
				w = wantLines[i]
			}
			if g != w {
				t.Errorf("  line %d:\n   got %q\n  want %q", i, g, w)
				break
			}
		}
	}
}
