func init() {
	mathematicaM0 = &Mode{ClassName: "comment", Begin: "\\(\\*", End: "\\*\\)"}
	mathematicaM1 = &Mode{Begin: "\\b(a|an|the|are|I'm|isn't|don't|doesn't|won't|but|just|should|pretty|simply|enough|gonna|going|wtf|so|such|will|you|your|they|like|more)\\b"}
	mathematicaM2 = &Mode{ClassName: "doctag", Begin: "(?:TODO|FIXME|NOTE|BUG|OPTIMIZE|HACK|XXX):", HasRelevance: true, Relevance: 0}
	mathematicaM3 = &Mode{ClassName: "pattern", Begin: "([a-zA-Z$][a-zA-Z0-9$]*)?_+([a-zA-Z$][a-zA-Z0-9$]*)?", HasRelevance: true, Relevance: 0}
	mathematicaM4 = &Mode{ClassName: "slot", Begin: "#[a-zA-Z$][a-zA-Z0-9$]*|#+[0-9]?", HasRelevance: true, Relevance: 0}
	mathematicaM5 = &Mode{ClassName: "message-name", Begin: "::[a-zA-Z$][a-zA-Z0-9$]*", HasRelevance: true, Relevance: 0}
	mathematicaM6 = &Mode{}
	mathematicaM7 = &Mode{ClassName: "builtin-symbol", Begin: "[a-zA-Z$][a-zA-Z0-9$]*"}
	mathematicaM8 = &Mode{ClassName: "symbol", Begin: "[a-zA-Z$][a-zA-Z0-9$]*", HasRelevance: true, Relevance: 0}
	mathematicaM9 = &Mode{ClassName: "named-character", Begin: "\\\\\\[[$a-zA-Z][$a-zA-Z0-9]+\\]"}
	mathematicaM10 = &Mode{ClassName: "string", Illegal: "\\n", Begin: "\"", End: "\""}
	mathematicaM11 = &Mode{Begin: "\\\\[\\s\\S]", HasRelevance: true, Relevance: 0}
	mathematicaM12 = &Mode{ClassName: "number", Begin: "(([2-9]|[1-2]\\d|[3][0-5])\\^\\^(\\w*\\.\\w+|\\w+\\.\\w*|\\w+)|(\\d*\\.\\d+|\\d+\\.\\d*|\\d+))((``[+-]?(\\d*\\.\\d+|\\d+\\.\\d*|\\d+)|`([+-]?(\\d*\\.\\d+|\\d+\\.\\d*|\\d+))?))?(\\*\\^[+-]?\\d+)?", HasRelevance: true, Relevance: 0}
	mathematicaM13 = &Mode{ClassName: "operator", Begin: "[+\\-*/,;.:@~=><&|_`'^?!%]+", HasRelevance: true, Relevance: 0}
	mathematicaM14 = &Mode{ClassName: "brace", Begin: "[[\\](){}]", HasRelevance: true, Relevance: 0}
	mathematicaM0.Contains = []*Mode{Self, mathematicaM1, mathematicaM2}
	mathematicaM6.Variants = []*Mode{mathematicaM7, mathematicaM8}
	mathematicaM10.Contains = []*Mode{mathematicaM11}
	mathematicaM7.OnBegin = func(m *match, resp *Response) {
		if !mathematicaSystemSymbols[m.lexeme] {
			resp.IgnoreMatch()
		}
	}
	RegisterLanguage("mathematica", &Language{
		Name:             "Mathematica",
		Aliases:          []string{"mma", "wl"},
		CaseInsensitive:  false,
		ClassNameAliases: map[string]string{"brace": "punctuation", "pattern": "type", "slot": "type", "symbol": "variable", "named-character": "variable", "builtin-symbol": "built_in", "message-name": "string"},
		Mode:             Mode{Contains: []*Mode{mathematicaM0, mathematicaM3, mathematicaM4, mathematicaM5, mathematicaM6, mathematicaM9, mathematicaM10, mathematicaM12, mathematicaM13, mathematicaM14}},
	})
}

